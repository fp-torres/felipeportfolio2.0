// Bundles every Iconify icon referenced in src/ at build time, so icons render offline instead of being fetched
// from api.iconify.design at runtime. Runs automatically before `dev` and `build` and writes two modules:
// - src/lib/icons.generated.js: the icons of the code every visitor loads (imported by main.jsx and entry-server.jsx);
// - src/lib/icons.lazy.generated.js: the icons used only by the lazy chunks (games, Laboratório, CV sheet), kept out
//   of the main bundle. src/lib/lazyWithRetry.js loads it together with each lazy component.
// Icon names must appear as full literals ("solar:close-linear") in the code of a file in src/ to be found.
// Names that only appear inside comments are ignored (and listed), so a note such as "instead of the heavy
// devicon:linux" never ships that icon to every visitor.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { getIcons } from '@iconify/utils';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src');
const outFile = join(srcDir, 'lib', 'icons.generated.js');
const lazyOutFile = join(srcDir, 'lib', 'icons.lazy.generated.js');
const setsDir = join(root, 'node_modules', '@iconify-json');

// Where the code every visitor loads starts: the browser entry and the pre-render entry (scripts/prerender.mjs).
const ENTRIES = ['src/main.jsx', 'src/entry-server.jsx'];

// Code that only runs inside a chunk loaded through lazyWithRetry(() => import(...)): the games, the Laboratório
// sheets and the CV sheet. A file here that the eager code also imports statically (games/records.js is read by
// GameHub, lab/LabStatus.jsx by the Footer) is reached by following the imports from ENTRIES and stays eager.
const LAZY_PATHS = [
  'src/components/games/',
  'src/components/lab/',
  'src/components/CvModal.jsx',
  'src/components/NasaModal.jsx',
  'src/components/NasaTimeMachine.jsx',
  'src/components/TechNews.jsx',
];

const HEADER = '// Generated by scripts/build-icons.mjs — do not edit by hand.\n';
const LAZY_NOTE = '// Icons used only by lazy chunks; src/lib/lazyWithRetry.js loads this module with each lazy component.\n';

function moduleSource(collections, note = '') {
  const body = collections.map((collection) => `addCollection(${JSON.stringify(collection)});`).join('\n');
  if (!body) return `${HEADER}${note}export {};\n`;
  return `${HEADER}${note}import { addCollection } from '@iconify/react';\n\n${body}\n`;
}

// Unchanged content is not rewritten, so a running dev server doesn't reload the page for nothing.
function write(file, source) {
  if (existsSync(file) && readFileSync(file, 'utf8') === source) return;
  writeFileSync(file, source);
}

const prefixes = existsSync(setsDir) ? readdirSync(setsDir) : [];
if (prefixes.length === 0) {
  console.warn('[icons] no @iconify-json/* packages installed — skipping');
  // The app imports both modules: keep them resolvable (icons then come from the Iconify API at runtime).
  if (!existsSync(outFile)) writeFileSync(outFile, moduleSource([]));
  if (!existsSync(lazyOutFile)) writeFileSync(lazyOutFile, moduleSource([], LAZY_NOTE));
  process.exit(0);
}

// Longest prefixes first so "devicon-plain:x" is not read as "devicon".
const alternation = [...prefixes]
  .sort((a, b) => b.length - a.length)
  .map((prefix) => prefix.replace(/[-]/g, '\\-'))
  .join('|');
const iconPattern = new RegExp(`(?<![\\w-])(${alternation}):([a-z0-9]+(?:-[a-z0-9]+)*)`, 'g');

// Static imports and re-exports (`import x from './a'`, `import './a'`, `export { y } from './b'`), never import().
const staticImportPattern = /(?:^|[\n;])\s*(?:import|export)\b\s*(?:[\w$*{},\s]+?\s*from\s*)?['"]([^'"\n]+)['"]/g;

function* sourceFiles(dir) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) yield* sourceFiles(path);
    else if (/\.(jsx?|tsx?)$/.test(entry) && path !== outFile && path !== lazyOutFile) yield path;
  }
}

const files = [...sourceFiles(srcDir)];
const known = new Set(files);
const EXTENSIONS = ['.js', '.jsx', '.ts', '.tsx'];
const CANDIDATE_SUFFIXES = ['', ...EXTENSIONS, ...EXTENSIONS.map((ext) => `${sep}index${ext}`)];

// The file of src/ a relative ('./a', '../b') or root ('/src/c') specifier points to, as Vite resolves it.
function resolveSource(from, specifier) {
  if (!/^\.{0,2}\//.test(specifier)) return null; // packages ('react', '@iconify/react') hold no code of src/
  const path = specifier.split(/[?#]/, 1)[0];
  const base = path.startsWith('/') ? join(root, path) : resolve(dirname(from), path);
  return CANDIDATE_SUFFIXES.map((suffix) => base + suffix).find((candidate) => known.has(candidate)) ?? null;
}

// Comments are dropped with esbuild (through Vite, already a dependency; JSX kept as is). Fail-safe: when Vite or the
// parse of a file is unavailable, the raw text of that file is scanned, which can only add icons (and eager files),
// never drop one.
let transformWithEsbuild = null;
try {
  ({ transformWithEsbuild } = await import('vite'));
} catch {
  console.warn('[icons] vite unavailable — names inside comments are bundled too');
}

async function codeWithoutComments(file, text) {
  if (!transformWithEsbuild) return text;
  const loader = file.slice(file.lastIndexOf('.') + 1);
  try {
    const { code } = await transformWithEsbuild(text, file, {
      loader,
      jsx: 'preserve',
      legalComments: 'none',
      charset: 'utf8',
      sourcemap: false,
    });
    return code;
  } catch {
    return text;
  }
}

const scanned = new Map();
const inComments = new Set();
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  const code = await codeWithoutComments(file, text);
  const icons = new Set(Array.from(code.matchAll(iconPattern), ([literal]) => literal));
  for (const [literal] of text.matchAll(iconPattern)) {
    if (!icons.has(literal)) inComments.add(literal);
  }
  const imports = Array.from(code.matchAll(staticImportPattern), ([, specifier]) => resolveSource(file, specifier));
  scanned.set(file, { icons, imports: imports.filter(Boolean) });
}

// Everything the entries reach through static imports runs for every visitor.
const entries = ENTRIES.map((entry) => join(root, entry)).filter((file) => known.has(file));
if (entries.length === 0) console.warn(`[icons] ${ENTRIES.join(', ')} not found — every icon goes to the main bundle`);
const eager = new Set();
const queue = [...entries];
while (queue.length > 0) {
  const file = queue.pop();
  if (eager.has(file)) continue;
  eager.add(file);
  queue.push(...scanned.get(file).imports);
}

const inLazyPath = (file) => {
  const path = relative(root, file).split(sep).join('/');
  return LAZY_PATHS.some((lazyPath) => (lazyPath.endsWith('/') ? path.startsWith(lazyPath) : path === lazyPath));
};
const isLazy = (file) => entries.length > 0 && !eager.has(file) && inLazyPath(file);

const eagerIcons = new Set();
const lazyIcons = new Set();
for (const [file, { icons }] of scanned) {
  const target = isLazy(file) ? lazyIcons : eagerIcons;
  for (const literal of icons) target.add(literal);
}
for (const literal of eagerIcons) lazyIcons.delete(literal);

const commentOnly = [...inComments].filter((literal) => !eagerIcons.has(literal) && !lazyIcons.has(literal));
if (commentOnly.length > 0) {
  console.log(`[icons] ignored, only mentioned in comments: ${commentOnly.sort().join(', ')}`);
}
const keptEager = [...scanned]
  .filter(([file, { icons }]) => icons.size > 0 && inLazyPath(file) && eager.has(file))
  .map(([file]) => relative(root, file));
if (keptEager.length > 0) {
  console.log(`[icons] in a lazy folder but imported statically by eager code: ${keptEager.sort().join(', ')}`);
}

// Flag the icons heavy enough to matter on a phone (the eager ones are downloaded by every visitor).
const HEAVY_ICON_BYTES = 12 * 1024;

const iconSets = new Map();
async function iconSet(prefix) {
  if (!iconSets.has(prefix)) iconSets.set(prefix, (await import(`@iconify-json/${prefix}`)).icons);
  return iconSets.get(prefix);
}

async function bundle(literals) {
  const wanted = new Map();
  for (const literal of literals) {
    const [prefix, name] = literal.split(':');
    if (!wanted.has(prefix)) wanted.set(prefix, new Set());
    wanted.get(prefix).add(name);
  }

  const collections = [];
  let total = 0;
  let bytes = 0;
  for (const [prefix, names] of [...wanted].sort(([a], [b]) => a.localeCompare(b))) {
    const subset = getIcons(await iconSet(prefix), [...names].sort(), true);
    if (!subset) continue;
    if (subset.not_found?.length) {
      console.warn(`[icons] not found in ${prefix}: ${subset.not_found.join(', ')}`);
      delete subset.not_found;
    }
    for (const [name, icon] of Object.entries(subset.icons)) {
      bytes += icon.body.length;
      if (icon.body.length > HEAVY_ICON_BYTES) {
        console.warn(`[icons] ${prefix}:${name} is ${Math.round(icon.body.length / 1024)} KB — prefer a lighter icon`);
      }
    }
    total += Object.keys(subset.icons).length;
    collections.push(subset);
  }
  return { collections, total, bytes };
}

for (const [file, literals, note, where] of [
  [outFile, eagerIcons, '', 'main bundle'],
  [lazyOutFile, lazyIcons, LAZY_NOTE, 'lazy chunks only'],
]) {
  const { collections, total, bytes } = await bundle(literals);
  const source = moduleSource(collections, note);
  write(file, source);
  const size = `${Math.round(bytes / 1024)} KB of SVG, ${(gzipSync(source).length / 1024).toFixed(1)} KB gz`;
  console.log(`[icons] ${total} icons from ${collections.length} sets (${size}) → ${relative(root, file)} (${where})`);
}
